			<h2 class="font-bold text-foreground text-sm uppercase tracking-wide mb-2">Dataansvarlig</h2>
			<p>LejeMatch er dataansvarlig for de personoplysninger, vi behandler om dig som bruger af platformen.</p>
		</section>

		<section>
			<h2 class="font-bold text-foreground text-sm uppercase tracking-wide mb-2">Hvilke oplysninger indsamler vi</h2>
			<p>
				Når du opretter en konto, indsamler vi navn, e-mail, telefonnummer og by. Når du opretter et opslag,
				gemmer vi de oplysninger og billeder, du selv vælger at dele. Når du kontakter en anden bruger,
				gemmer vi beskeden, så modtageren kan se den i sit dashboard.
			</p>
		</section>

		<section>
			<h2 class="font-bold text-foreground text-sm uppercase tracking-wide mb-2">Hvad bruger vi oplysningerne til</h2>
			<p>
				Oplysningerne bruges udelukkende til at drive platformen: at vise dine opslag til andre brugere,
				lade andre kontakte dig, og sende dig relevante e-mails (f.eks. e-mailbekræftelse eller nulstilling
				af adgangskode).
			</p>
		</section>

		<section>
			<h2 class="font-bold text-foreground text-sm uppercase tracking-wide mb-2">Dine rettigheder</h2>
			<p>
				Du kan til enhver tid se og redigere dine oplysninger under "Indstillinger", eller slette din konto
				permanent. Du har derudover ret til indsigt, berigtigelse og sletning af dine personoplysninger
				efter databeskyttelsesforordningen (GDPR).
			</p>
		</section>

		<section>
			<h2 class="font-bold text-foreground text-sm uppercase tracking-wide mb-2">Sletning af data</h2>
			<p>
				Når du sletter din profil, sletter vi permanent alle dine personoplysninger fra vores systemer —
				herunder din profil, dine opslag (boliger og lejerprofiler), billeder tilknyttet dine opslag,
				favoritter og beskeder du har sendt eller modtaget. Sletningen kan ikke fortrydes.
			</p>
		</section>

		<section>
			<h2 class="font-bold text-foreground text-sm uppercase tracking-wide mb-2">Kontakt</h2>
